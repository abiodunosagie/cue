// Projects: the folder scan, what is stored, and what reaches a prompt.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const {
  parsePackageJson, parsePubspec, readmeExcerpt, siteDescription, parseGitLog, ownershipOf,
  parseProjectsIndex, yearsLabel, prettyName, scanProjects
} = require('../src/projects-scan');
const { normalizeProjects, buildProjectsBlock, mentionedProjects, usedProjects, DIGEST_MAX_CHARS } = require('../src/projects');
const { parseDrafts, projectText, draftProjects } = require('../src/project-draft');
const { buildInterviewContext } = require('../src/interview-context');

test('package.json: name, description and the stack in framework-first order', () => {
  const p = parsePackageJson(JSON.stringify({
    name: 'shop', description: 'A shop',
    dependencies: { '@supabase/supabase-js': '1', react: '19', next: '16', 'react-paystack': '1', lodash: '4' },
    devDependencies: { typescript: '5' }
  }));
  assert.equal(p.name, 'shop');
  assert.deepEqual(p.stack, ['Next.js', 'React', 'TypeScript', 'Supabase', 'Paystack']);
  assert.equal(parsePackageJson('{broken'), null);
});

test('pubspec.yaml: dependencies are read, the Flutter template description is dropped', () => {
  const p = parsePubspec('name: beepex\ndescription: "A new Flutter project."\nenvironment:\n  sdk: ">=3.0.0"\ndependencies:\n  flutter:\n    sdk: flutter\n  flutter_riverpod: ^2.0.0\n  supabase_flutter: ^2.0.0\ndev_dependencies:\n  mocktail: ^1.0.0\n');
  assert.equal(p.name, 'beepex');
  assert.equal(p.description, '');
  assert.deepEqual(p.stack, ['Flutter', 'Dart', 'Riverpod', 'Supabase', 'Tests']);
});

test('a README excerpt skips headings, badges, templates and anything private', () => {
  const md = [
    '# Evvy', '![badge](x.svg)', '',
    'Online store for hair products with Paystack checkout.', '',
    '[Features](#features) • [Setup](#setup)', '',
    'First, run the development server:', '', '```bash', 'npm run dev', '```', '',
    'Open [http://localhost:3000](http://localhost:3000) with your browser to see the result.', '',
    'The internal session guide is at ~/Documents/guide.md for the team.', '',
    'Set STRIPE_SECRET in your environment before running it locally, please.'
  ].join('\n');
  assert.equal(readmeExcerpt(md), 'Online store for hair products with Paystack checkout.');
  assert.equal(readmeExcerpt(''), '');
});

test('the public site description is read from a layout; the template one is ignored', () => {
  assert.equal(siteDescription('export const metadata = { title: "X", description: "Practice management for clinics." }'), 'Practice management for clinics.');
  assert.equal(siteDescription('description: "Generated by create next app"'), '');
  assert.equal(siteDescription('nothing here'), '');
});

test('git log: commit counts per author, dates, and the candidate\'s share by their own emails', () => {
  const g = parseGitLog('me@x.com\t1700000000\nME@x.com\t1710000000\nother@y.com\t1690000000\nbad line\n');
  assert.equal(g.total, 3);
  assert.equal(g.authors.get('me@x.com'), 2);
  assert.equal(g.first, 1690000000 * 1000);
  assert.deepEqual(ownershipOf(g, new Set(['me@x.com'])), { mine: 2, total: 3, share: 2 / 3 });
  assert.deepEqual(ownershipOf(null, new Set()), { mine: 0, total: 0, share: 0 });
  assert.equal(yearsLabel(Date.UTC(2024, 5), Date.UTC(2026, 1)), '2024 to 2026');
  assert.equal(yearsLabel(Date.UTC(2026, 1), Date.UTC(2026, 5)), '2026');
  assert.equal(prettyName('votixcare-admin'), 'Votixcare Admin');
});

test('the projects index maps each repo to the identity the owner commits under', () => {
  const map = parseProjectsIndex('| VotixCare | `~/Projects/web/votixcare-app` | main | VotixCare <votixcare@gmail.com> | org |\n| junk |', '/Users/a');
  assert.equal(map.get('/Users/a/Projects/web/votixcare-app'), 'votixcare@gmail.com');
  assert.equal(map.size, 1);
});

test('scanning a folder reads only the allowed files and never a secret', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cue-proj-'));
  const app = path.join(root, 'web', 'shop');
  fs.mkdirSync(path.join(app, 'src', 'app'), { recursive: true });
  fs.mkdirSync(path.join(app, 'node_modules'));
  fs.writeFileSync(path.join(app, 'package.json'), JSON.stringify({ dependencies: { next: '16', react: '19' } }));
  fs.writeFileSync(path.join(app, 'README.md'), 'A shop that sells shoes online to customers in Lagos.');
  fs.writeFileSync(path.join(app, '.env'), 'SECRET_KEY=abc123');
  fs.writeFileSync(path.join(app, 'SESSION_GUIDE.md'), 'Private guide with keys.');
  fs.writeFileSync(path.join(app, 'src', 'app', 'layout.tsx'), 'export const metadata = { description: "Shoe shop for Lagos." }; const KEY = "abc123";');
  fs.mkdirSync(path.join(root, 'web', 'notes'));   // not a project: no git, package.json or pubspec
  const found = await scanProjects({ root, home: os.homedir(), ownEmails: [] });
  assert.equal(found.length, 1);
  const p = found[0];
  assert.equal(p.id, path.join('web', 'shop'));
  assert.equal(p.category, 'web');
  assert.equal(p.name, 'Shop');
  assert.deepEqual(p.stack, ['Next.js', 'React']);
  assert.equal(p.description, 'Shoe shop for Lagos.');
  assert.deepEqual(p.folders, ['src']);
  assert.doesNotMatch(JSON.stringify(found), /abc123|Private guide/);
  fs.rmSync(root, { recursive: true, force: true });
});

const sample = [
  { id: 'mobile/beepex', name: 'Beepex', stack: ['Flutter', 'Riverpod'], years: '2025 to 2026', summary: 'Fintech app for airtime, bills and gift cards.', details: 'Paystack wallet funding.', role: 'Built the Flutter app.', use: true },
  { id: 'web/votixcare-app', name: 'Votixcare App', stack: ['Next.js'], summary: 'Clinic dashboard for optometry practices.', role: 'Built it end to end.', use: true },
  { id: 'web/hidden', name: 'Hidden', summary: 'Not approved.', use: false },
  { id: 'web/empty', name: 'Empty', summary: '', use: true }
];

test('stored projects are cleaned: bad entries dropped, fields cut, em dashes removed', () => {
  const out = normalizeProjects([{ id: 'a', name: 'A', summary: 'One — two', use: 'yes', stack: ['x', '', 5] }, { id: 'a' }, null, { name: 'no id' }]);
  assert.equal(out.length, 1);
  assert.equal(out[0].summary, 'One, two');
  assert.equal(out[0].use, false);
  assert.deepEqual(out[0].stack, ['x', '5']);
  assert.deepEqual(normalizeProjects('nope'), []);
});

test('only approved projects with a summary reach the prompt, fenced as data', () => {
  const block = buildProjectsBlock(sample);
  assert.match(block, /<projects>/);
  assert.match(block, /- Beepex \(Flutter, Riverpod; 2025 to 2026\): Fintech app/);
  assert.match(block, /My role: Built the Flutter app\./);
  assert.doesNotMatch(block, /Hidden|Empty/);
  assert.match(block, /Never invent/);
  assert.equal(buildProjectsBlock([]), '');
  assert.equal(buildProjectsBlock(undefined), '');
  const many = Array.from({ length: 200 }, (_, i) => ({ id: 'p' + i, name: 'Project ' + i, summary: 'x'.repeat(250), use: true }));
  assert.ok(buildProjectsBlock(many).length < DIGEST_MAX_CHARS + 1500);
});

test('a project the interviewer names gets its full notes; one already used is flagged', () => {
  const transcript = [{ channel: 'them', text: 'Tell me more about VotixCare, how did you build it?' }];
  assert.deepEqual(mentionedProjects(normalizeProjects(sample).filter((p) => p.use), transcript).map((p) => p.name), ['Votixcare App']);
  const block = buildProjectsBlock(sample, { transcript, answerTexts: ['On Beepex I built the wallet.'] });
  assert.match(block, /<project_notes>[\s\S]*Votixcare App[\s\S]*What it is: Clinic dashboard/);
  assert.match(block, /Already used as examples in this interview: Beepex\./);
  // Common words never count as a mention.
  assert.deepEqual(usedProjects(normalizeProjects([{ id: 'x', name: 'Web App', summary: 's', use: true }]), ['I built a web app']), []);
  assert.deepEqual(usedProjects(normalizeProjects([{ id: 'x', name: 'Evvy Admin', summary: 's', use: true }]), ['the admin panel']), []);
});

test('the interview context carries the projects block, except for coding and salary', () => {
  const settings = { resumeText: 'Engineer', projects: sample };
  assert.match(buildInterviewContext(settings, 'say', [{ channel: 'them', text: 'Tell me about a project you built.' }]), /Your projects/);
  assert.equal(buildInterviewContext(settings, 'leetcode', []), null);
  assert.doesNotMatch(buildInterviewContext(settings, 'say', [{ channel: 'them', text: 'What are your salary expectations?' }]) || '', /Your projects/);
});

test('AI drafts: parsed per id, unknown ids dropped, em dashes removed, bad replies fail plainly', () => {
  const d = parseDrafts('ok {"projects":[{"id":"a","summary":"Shop — for Lagos.","details":"Uses Next.js."},{"id":"zzz","summary":"x"},{"id":"b","summary":""}]}', ['a', 'b']);
  assert.deepEqual(d, { a: { summary: 'Shop, for Lagos.', details: 'Uses Next.js.' } });
  assert.throws(() => parseDrafts('no json', ['a']), /did not return project notes/);
  assert.match(projectText({ id: 'a"b', name: 'Shop', stack: ['Next.js'], folders: ['src'], readme: '' }), /<project id="ab">[\s\S]*README introduction: \(none\)/);
});

test('drafting runs in batches and keeps the good batches when one fails', async () => {
  const projects = Array.from({ length: 8 }, (_, i) => ({ id: 'p' + i, name: 'P' + i }));
  let call = 0;
  const quickAsk = async ({ text }) => {
    call += 1;
    if (call === 2) throw new Error('timeout');
    const ids = [...text.matchAll(/<project id="([^"]+)">/g)].map((m) => m[1]);
    return JSON.stringify({ projects: ids.map((id) => ({ id, summary: 'About ' + id, details: '' })) });
  };
  const out = await draftProjects({ projects, llm: { ready: true }, quickAsk });
  assert.equal(Object.keys(out.drafts).length, 6);
  assert.equal(out.failed, 2);
  await assert.rejects(draftProjects({ projects, llm: { ready: false }, quickAsk }), /Smart model/);
});
