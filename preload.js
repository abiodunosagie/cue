const { contextBridge, ipcRenderer } = require('electron');
const platform = process.platform;

contextBridge.exposeInMainWorld('cue', {
  platform,
  settingsGet: () => ipcRenderer.invoke('settings:get'),
  settingsSet: (patch) => ipcRenderer.invoke('settings:set', patch),
  whisperModels: () => ipcRenderer.invoke('whisper:models'),
  whisperModelDownload: (modelId) => ipcRenderer.invoke('whisper:model-download', modelId),
  whisperModelCancel: (modelId) => ipcRenderer.invoke('whisper:model-cancel', modelId),
  whisperModelDelete: (modelId) => ipcRenderer.invoke('whisper:model-delete', modelId),
  whisperModelImport: (modelId) => ipcRenderer.invoke('whisper:model-import', modelId),
  platformInfo: () => ipcRenderer.invoke('platform:info'),
  ask: (payload) => ipcRenderer.send('ask', payload),
  captureToggle: () => ipcRenderer.invoke('capture:toggle').catch((err) => {
    console.error('[cue] captureToggle error', err);
    return false;
  }),
  captureState: () => ipcRenderer.invoke('capture:state'),
  micPcm: (arrayBuffer) => ipcRenderer.send('mic:pcm', arrayBuffer),
  systemPcm: (arrayBuffer) => ipcRenderer.send('system:pcm', arrayBuffer),
  setIgnoreMouse: (v) => ipcRenderer.send('mouse:ignore', v),
  clearTranscript: () => ipcRenderer.invoke('transcript:clear'),
  nextQuestion: () => ipcRenderer.send('question:next'),
  scriptActive: (on) => ipcRenderer.send('script:active', !!on),
  scriptReview: (text) => ipcRenderer.invoke('script:review', text),
  projectsGet: () => ipcRenderer.invoke('projects:get'),
  projectsScan: () => ipcRenderer.invoke('projects:scan'),
  projectsSave: (list) => ipcRenderer.invoke('projects:save', list),
  projectsDraft: (ids) => ipcRenderer.invoke('projects:draft', ids),
  codingLibraryGet: () => ipcRenderer.invoke('codingLibrary:get'),
  recordInfo: () => ipcRenderer.invoke('record:info'),
  projectDetect: () => ipcRenderer.invoke('project:detect'),
  projectStart: (source) => ipcRenderer.invoke('project:start', source),
  projectClear: () => ipcRenderer.invoke('project:clear'),
  projectShow: () => ipcRenderer.invoke('project:show'),
  recordBegin: (opts) => ipcRenderer.invoke('record:begin', opts),
  recordChunk: (id, data) => ipcRenderer.invoke('record:chunk', id, data),
  recordEnd: (id, opts) => ipcRenderer.invoke('record:end', id, opts),
  recordReveal: (p) => ipcRenderer.invoke('record:reveal', p),
  recordDiscard: (p) => ipcRenderer.invoke('record:discard', p),
  recordChooseFolder: () => ipcRenderer.invoke('record:choose-folder'),
  recordPlace: (on) => ipcRenderer.invoke('record:place', on),
  codingLibraryDelete: (id) => ipcRenderer.invoke('codingLibrary:delete', id),
  memoryState: () => ipcRenderer.invoke('memory:state'),
  preparedState: () => ipcRenderer.invoke('prepared:state'),
  preparedRun: () => ipcRenderer.invoke('prepared:run'),
  practiceStart: () => ipcRenderer.invoke('practice:start'),
  setupTest: () => ipcRenderer.invoke('setup:test'),
  profileSwitch: (name) => ipcRenderer.invoke('profile:switch', name),
  profileCreate: (name) => ipcRenderer.invoke('profile:create', name),
  profileDeleteCurrent: () => ipcRenderer.invoke('profile:delete-current'),
  companyResearch: (url) => ipcRenderer.invoke('company:research', url),
  practiceNext: () => ipcRenderer.invoke('practice:next'),
  practiceEnd: () => ipcRenderer.invoke('practice:end'),
  practicePlayed: (token) => ipcRenderer.send('practice:played', token),
  openPane: (url) => ipcRenderer.send('open-pane', url),
  publikState: () => ipcRenderer.invoke('publik:state'),
  publikAcceptDisclosure: () => ipcRenderer.invoke('publik:accept-disclosure'),
  publikReconnect: () => ipcRenderer.invoke('publik:reconnect'),
  publikRefresh: () => ipcRenderer.invoke('publik:refresh'),
  publikDisconnect: () => ipcRenderer.invoke('publik:disconnect'),
  publikCardSeen: () => ipcRenderer.invoke('publik:card-seen'),
  publikOpen: (url) => ipcRenderer.send('publik:open', url),
  appLinkState: () => ipcRenderer.invoke('applink:state'),
  appLinkRevoke: (callerId) => ipcRenderer.invoke('applink:revoke', callerId),
  appLinkConsentRespond: (id, allowed) => ipcRenderer.send('applink:consent-response', { id, allowed }),
  pickProfileDocument: () => ipcRenderer.invoke('profile:pickDocument'),
  quit: () => ipcRenderer.send('app:quit'),
  permissionsCheck: () => ipcRenderer.invoke('permissions:check'),
  permissionsRequest: () => ipcRenderer.invoke('permissions:request'),
  permissionsContinue: () => ipcRenderer.send('permissions:continue'),
  copyText: (text) => ipcRenderer.invoke('clipboard:write', text),
  log: (msg) => ipcRenderer.send('log', msg),
  on: (channel, cb) => {
    const allowed = ['capture:state', 'llm:start', 'llm:token', 'llm:done', 'llm:error', 'status', 'transcript', 'stt:interim', 'stt:final', 'stt:status', 'vad:state', 'applink:consent-request', 'hide:toggle', 'length:changed', 'scrollReading:changed', 'question:changed', 'script:heard', 'answer:scroll', 'llm:thinking', 'llm:section', 'code:copy', 'llm:tag', 'prepared:state', 'practice:state', 'practice:play', 'practice:cleared', 'setup:result', 'whisper:download-progress', 'whisper:models-changed', 'publik:state', 'projects:draft-progress'];
    if (!allowed.includes(channel)) return;
    ipcRenderer.on(channel, (_e, data) => cb(data));
  }
});
